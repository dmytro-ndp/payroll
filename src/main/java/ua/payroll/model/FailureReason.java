package ua.payroll.model;

/**
 * Причина відмови операції моделі. Не містить кодів HTTP — відображення причини
 * на код виконує лише вигляд (принцип XI).
 */
public enum FailureReason {
    /** Дані не пройшли перевірку (R1, R2, R3). */
    VALIDATION,
    /** Об'єкт не знайдено (R5). */
    NOT_FOUND,
    /** Зміну заборонено — наказ нечинний (R4). */
    FORBIDDEN,
    /** Збій сховища даних. */
    STORAGE_ERROR
}
